"""The data center's committed data dictionaries and formula definitions equal a fresh build's.

The data center's two promoted artifacts, ``data_center/models/space/default.json`` and
``data_center/models/ground/default.json``, describe themselves in their ``meta`` blocks: each
artifact's ``meta.data_dictionary`` (one entry per published field, generated by the shared
walker) and the space artifact's ``meta.formula_definitions`` (one entry per formula of the data
center's catalog). These tests catch a change to the walker or to the catalog that would describe
the same model differently from the committed files, without re-promoting the data center.

The sample: the default scenario ``code/scenarios/default.yaml`` and the default ground
assumptions ``code/scenarios/ground_default.yaml``, built as ``rklb-value --promote`` builds them
(``data_center.cli._promote``): the space run through :func:`data_center.engine.run_valuation`
under the default scenario's repository path with the ``promoted_default`` role, the ground
reference through :func:`data_center.ground.build_ground_reference_output` with the space
artifact's and the ground scenario's repository paths, each serialized by
:func:`common.file_io.render_artifact_json` and parsed. What counts as success: each committed
block, parsed as JSON, equals the fresh build's whole (every entry, in order).

``-k committed_meta`` selects every test here, by this module's name.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from common.file_io import render_artifact_json
from data_center.cli import (
    DEFAULT_OUTPUT_NAME,
    GROUND_MODELS_SUBDIR,
    PROMOTED_MODELS_DIR,
    SPACE_MODELS_SUBDIR,
)
from data_center.config import load_config
from data_center.engine import run_valuation
from data_center.ground import (
    DEFAULT_GROUND_SCENARIO_PATH,
    build_ground_reference_output,
    load_ground_config,
)
from data_center.input_manifest import DEFAULT_SCENARIO_PATH
from data_center.output import ArtifactRole, SpaceModelOutput

SPACE_ARTIFACT_PATH = f"{PROMOTED_MODELS_DIR}/{SPACE_MODELS_SUBDIR}/{DEFAULT_OUTPUT_NAME}.json"
"""The committed space artifact's repository path, as the default promotion names it."""

GROUND_ARTIFACT_PATH = f"{PROMOTED_MODELS_DIR}/{GROUND_MODELS_SUBDIR}/{DEFAULT_OUTPUT_NAME}.json"
"""The committed ground reference's repository path, as the default promotion names it."""


@pytest.fixture(scope="module")
def fresh_space_output(repo_dir: Path) -> SpaceModelOutput:
    """The default space run, built as the default promotion builds it."""
    return run_valuation(
        load_config(repo_dir / DEFAULT_SCENARIO_PATH),
        source_scenario_path=DEFAULT_SCENARIO_PATH,
        artifact_role=ArtifactRole.PROMOTED_DEFAULT,
    )


@pytest.fixture(scope="module")
def fresh_space(fresh_space_output: SpaceModelOutput) -> dict[str, Any]:
    """The fresh space artifact, serialized as the promotion writes it, then parsed."""
    parsed: dict[str, Any] = json.loads(render_artifact_json(fresh_space_output))
    return parsed


@pytest.fixture(scope="module")
def fresh_ground(repo_dir: Path, fresh_space_output: SpaceModelOutput) -> dict[str, Any]:
    """The fresh ground reference, built from the fresh space run as the promotion builds it."""
    ground = build_ground_reference_output(
        fresh_space_output,
        load_ground_config(repo_dir / DEFAULT_GROUND_SCENARIO_PATH),
        space_model_path=SPACE_ARTIFACT_PATH,
        ground_scenario_path=DEFAULT_GROUND_SCENARIO_PATH,
    )
    parsed: dict[str, Any] = json.loads(render_artifact_json(ground))
    return parsed


def _committed_meta(repo_dir: Path, artifact_path: str) -> dict[str, Any]:
    """Read one committed artifact from the repository and return its parsed ``meta`` block."""
    artifact: dict[str, Any] = json.loads((repo_dir / artifact_path).read_text(encoding="utf-8"))
    meta: dict[str, Any] = artifact["meta"]
    return meta


def _first_difference(
    committed: list[dict[str, Any]], fresh: list[dict[str, Any]], key: str
) -> str:
    """Say where a fresh block first departs from the committed one, for a failure message.

    Args:
        committed: The committed block's entries.
        fresh: The fresh build's entries.
        key: The field that names an entry (``path`` or ``formula_id``).

    Returns:
        The first entry that differs, named by its key with both versions, or the two
        lengths when every shared entry agrees.
    """
    for index, (old, new) in enumerate(zip(committed, fresh, strict=False)):
        if old != new:
            return f"entry {index} ({old.get(key)!r}) differs: committed {old!r}, fresh {new!r}"
    return f"the committed block has {len(committed)} entries, the fresh build {len(fresh)}"


def test_the_committed_space_data_dictionary_equals_a_fresh_build(
    repo_dir: Path, fresh_space: dict[str, Any]
) -> None:
    """Objective: the space artifact's committed data dictionary is the one the walker builds.

    Sample: ``data_center/models/space/default.json`` against the default scenario's fresh
    build. Expected: its ``meta.data_dictionary``, parsed, is not empty and equals the fresh
    build's whole: every entry's path, description, unit, type and source class, in order.
    """
    committed = _committed_meta(repo_dir, SPACE_ARTIFACT_PATH)["data_dictionary"]
    fresh = fresh_space["meta"]["data_dictionary"]
    assert committed, "the committed space artifact publishes no data dictionary"
    assert fresh == committed, _first_difference(committed, fresh, "path")


def test_the_committed_space_formula_definitions_equal_a_fresh_build(
    repo_dir: Path, fresh_space: dict[str, Any]
) -> None:
    """Objective: the space artifact's committed formula definitions are the catalog's today.

    Sample: ``data_center/models/space/default.json`` against the default scenario's fresh
    build. Expected: its ``meta.formula_definitions``, parsed, is not empty and equals the fresh
    build's whole: every formula's id, text, description, path patterns, unit behavior and
    notes, in order.
    """
    committed = _committed_meta(repo_dir, SPACE_ARTIFACT_PATH)["formula_definitions"]
    fresh = fresh_space["meta"]["formula_definitions"]
    assert committed, "the committed space artifact publishes no formula definitions"
    assert fresh == committed, _first_difference(committed, fresh, "formula_id")


def test_the_committed_ground_data_dictionary_equals_a_fresh_build(
    repo_dir: Path, fresh_ground: dict[str, Any]
) -> None:
    """Objective: the ground reference's committed data dictionary is the one the walker builds.

    Sample: ``data_center/models/ground/default.json`` against the ground reference built from
    the default scenario's fresh space run and the default ground assumptions. Expected: its
    ``meta.data_dictionary``, parsed, is not empty and equals the fresh build's whole: every
    entry's path, description, unit, type and source class, in order.
    """
    committed = _committed_meta(repo_dir, GROUND_ARTIFACT_PATH)["data_dictionary"]
    fresh = fresh_ground["meta"]["data_dictionary"]
    assert committed, "the committed ground reference publishes no data dictionary"
    assert fresh == committed, _first_difference(committed, fresh, "path")
